export const DEFAULT_RUNTIME_POLICY: RuntimePolicyMap = Object.fromEntries(
  DEFAULT_POLICIES.map((policy) => [
    makePolicyKey(policy.workloadType, policy.queueClass, policy.executionProfile),
    policy,
  ]),
);

export function resolveWorkloadPolicy(
  policyMap: RuntimePolicyMap,
  workloadType: string,
  queueClass?: WorkloadRuntimePolicy["queueClass"],
  executionProfile?: string,
): WorkloadRuntimePolicy | null {
  return (
    policyMap[makePolicyKey(workloadType, queueClass, executionProfile)]
    ?? policyMap[makePolicyKey(workloadType, queueClass)]
    ?? policyMap[makePolicyKey(workloadType)]
    ?? null
  );
}
